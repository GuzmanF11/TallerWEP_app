import type { Metadata } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import "./globals.css";
import { ThemeProvider } from "./theme-provider";
import { NotificationProvider } from "@/contexts/notification-context";
import { FloatingWindowsProvider } from "@/contexts/floating-windows-context";
import { FloatingWindowsRenderer } from "@/components/floating-windows-renderer";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "TallerWEP — Sistema de Gestión",
  description: "Sistema de inventario, compras y gestión para taller automotriz",
};

export default function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  return (
    <html lang="es" suppressHydrationWarning>
      <head>
        <script
          dangerouslySetInnerHTML={{
            __html: `(function(){try{var t=localStorage.getItem('theme');var d=t?t==='dark':window.matchMedia('(prefers-color-scheme: dark)').matches;document.documentElement.classList.toggle('dark',d);}catch(e){}})();`,
          }}
        />
      </head>
      <body
        className={`${geistSans.variable} ${geistMono.variable} antialiased`}
      >
        <ThemeProvider>
          <NotificationProvider>
            <FloatingWindowsProvider>
              {children}
              <FloatingWindowsRenderer />
            </FloatingWindowsProvider>
          </NotificationProvider>
        </ThemeProvider>
      </body>
    </html>
  );
}
